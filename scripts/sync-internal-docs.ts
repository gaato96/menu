/**
 * Copies the current marketing notes into src/content/internal/ so the
 * superadmin panel can show them:
 *   - marketing-docs.ts: the notes, one tab each, at /interno-64a0f7d0.
 *   - reel-packages.ts: each reel package and DM resource, opened one at a time
 *     from the content calendar (/interno-64a0f7d0/reel/<file>), never as tabs,
 *     so the notes page doesn't grow with every reel.
 *
 * The markdown lives in marketing/ and .agents/, outside what the deployed
 * server bundle can read at runtime, so the pages import generated modules
 * instead. Run `npm run docs:internal` after editing any of these notes, and
 * commit the generated files with them.
 *
 * Only what governs today goes here. Superseded documents live in
 * marketing/archivo/ and in git history, not in the panel.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(__dirname, "..");

// Tab order on the page: what you use every day first.
const DOCS: { key: string; label: string; file: string }[] = [
  { key: "panorama", label: "Panorama", file: "marketing/notas/02-panorama.md" },
  { key: "dia-por-dia", label: "Día por día", file: "marketing/notas/03-dia-por-dia.md" },
  { key: "adquisicion", label: "Prospección", file: "marketing/notas/02b-adquisicion.md" },
  { key: "mensajes-venta", label: "Mensajes", file: "marketing/ventas/mensajes.md" },
  { key: "respuestas", label: "Respuestas", file: "marketing/ventas/respuestas.md" },
  { key: "medicion", label: "Medición", file: "marketing/notas/05-medicion.md" },
  { key: "backlog", label: "Banco de ideas", file: "marketing/contenido/reels/backlog.md" },
  { key: "historias", label: "Historias", file: "marketing/contenido/historias/README.md" },
  { key: "produccion", label: "Producción", file: "marketing/contenido/reels/PRODUCCION.md" },
  { key: "plan", label: "Plan y oferta", file: "marketing/notas/01-plan.md" },
  { key: "contenido", label: "Contenido 90 días", file: "marketing/notas/04-contenido.md" },
  { key: "matriz", label: "Matriz", file: "marketing/investigacion/matriz-2026-11.md" },
  { key: "competencia", label: "Competencia", file: "marketing/investigacion/competencia-2026-11.md" },
  { key: "voz", label: "Voz del cliente", file: "marketing/investigacion/voz-del-cliente.md" },
  { key: "contexto", label: "Producto", file: ".agents/product-marketing.md" },
];

function leer(file: string): string | null {
  try {
    return readFileSync(join(root, file), "utf8");
  } catch {
    console.warn(`skip ${file} (not found)`);
    return null;
  }
}

function listMd(dir: string, only: RegExp = /./) {
  try {
    return readdirSync(join(root, dir))
      .filter((name) => name.endsWith(".md") && !name.startsWith("_") && only.test(name))
      .sort();
  } catch {
    return [];
  }
}

const docs = DOCS.flatMap((doc) => {
  const source = leer(doc.file);
  return source === null ? [] : [{ key: doc.key, label: doc.label, source }];
});

// Packages and resources, keyed by file name (what the calendar links to).
const paquetes: Record<string, { titulo: string; source: string }> = {};
for (const [dir, only] of [
  ["marketing/contenido/reels", /^\d/],
  ["marketing/contenido/recursos", /./],
] as const) {
  for (const name of listMd(dir, only)) {
    const source = leer(`${dir}/${name}`);
    if (source === null) continue;
    const titulo = source.match(/^#\s+(.+)$/m)?.[1] ?? name;
    paquetes[name] = { titulo, source };
  }
}

const cabecera = "// GENERATED by scripts/sync-internal-docs.ts — do not edit by hand.\n// Run `npm run docs:internal`.\n\n";

writeFileSync(
  join(root, "src/content/internal/marketing-docs.ts"),
  `${cabecera}export const marketingDocs: { key: string; label: string; source: string }[] = ${JSON.stringify(docs, null, 2)};\n`,
);
writeFileSync(
  join(root, "src/content/internal/reel-packages.ts"),
  `${cabecera}export const reelPackages: Record<string, { titulo: string; source: string }> = ${JSON.stringify(paquetes, null, 2)};\n`,
);
console.log(`wrote ${docs.length} notes and ${Object.keys(paquetes).length} packages`);
